-- D1 데이터베이스(cfa-pacer-db) 테이블
CREATE TABLE IF NOT EXISTS users (id INTEGER PRIMARY KEY AUTOINCREMENT, username TEXT UNIQUE NOT NULL, salt TEXT NOT NULL, hash TEXT NOT NULL, fails INTEGER NOT NULL DEFAULT 0, locked_until INTEGER NOT NULL DEFAULT 0, created INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS sessions (token_hash TEXT PRIMARY KEY, user_id INTEGER NOT NULL, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS data (user_id INTEGER PRIMARY KEY, body TEXT NOT NULL, updated_at INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS sessions_user ON sessions(user_id);
-- 비밀번호 찾기용 복구 코드 (해시만 저장)
ALTER TABLE users ADD COLUMN recovery_hash TEXT;
-- 구글 로그인
ALTER TABLE users ADD COLUMN google_sub TEXT;
ALTER TABLE users ADD COLUMN email TEXT;
ALTER TABLE users ADD COLUMN has_pw INTEGER NOT NULL DEFAULT 1;
CREATE UNIQUE INDEX IF NOT EXISTS users_google ON users(google_sub);
-- 이메일 인증
ALTER TABLE users ADD COLUMN email_verified INTEGER NOT NULL DEFAULT 0;
CREATE TABLE IF NOT EXISTS codes (id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER NOT NULL, purpose TEXT NOT NULL, code_hash TEXT NOT NULL, email TEXT, expires INTEGER NOT NULL, tries INTEGER NOT NULL DEFAULT 0, created INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS codes_user ON codes(user_id, purpose);
-- 매일 알림 (Web Push)
CREATE TABLE IF NOT EXISTS push_subs (id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER NOT NULL, endpoint TEXT UNIQUE NOT NULL, eph TEXT NOT NULL, times TEXT NOT NULL, tz INTEGER NOT NULL DEFAULT 540, msgs TEXT, last_slot TEXT, congrats TEXT, created INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS push_eph ON push_subs(eph);
